/**
 * Splits the Figma «horizon» element into its two pieces and optimizes them.
 *
 *   npm run horizon
 *
 * Input: design-audit/tmp/horizon.svg  (export of node 2012:4491)
 * Output:
 *   src/components/shared/horizon-wave.ts   the wave's two paths (inline)
 *   public/brand/sun-palm.svg               the medallion, as a file
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ⚠️ WHY IT'S SPLIT IN TWO INSTEAD OF USED AS A SINGLE SVG.
 *
 * The export comes as a single 77 KB piece, and that weight is distributed
 * very unevenly:
 *
 *     the two waves        1.4 KB   ← simple geometry
 *     the palm tree       20.1 KB
 *     the sun's teeth     52.5 KB   ← hundreds of tiny shapes
 *
 * And the two pieces need OPPOSITE things:
 *
 *   · **The wave** has to stretch to the full width of the screen and take its
 *     color from a token —it's the surface of the section below emerging—.
 *     That calls for inline SVG with `fill="currentColor"`. It's 1.4 KB: inline
 *     costs nothing.
 *   · **The medallion** has a fixed size, sits centered and its colors don't
 *     change. Inline it would be 72 KB in the home page HTML, uncached and
 *     repeated on every load. As a file it's cached once.
 *
 * ⚠️ THE FIGMA COLORS ARE NOT THE SITE'S and they have to be mapped: the export
 * carries `#003A3A` and `#FFF7ED`, which are a green and a bone similar to but
 * different from `deep` (#014545) and the palette here. They're translated to the tokens.
 * Leaving them as they come puts two off-palette colors in the middle of the home page.
 * ══════════════════════════════════════════════════════════════════════════
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';

/**
 * The palette is READ from `src/lib/brand.ts` instead of written here.
 *
 * ⚠️ It's the same lesson `scripts/contrast.mjs` left behind, which had the hexes
 * copied by hand and ended up measuring colors the site didn't paint. A script
 * that generates art with baked-in color has to read the source.
 */
const COLORS = Object.fromEntries(
  [...readFileSync('src/lib/brand.ts', 'utf8').matchAll(/^\s+'?([a-z-]+)'?:\s*'(#[0-9A-Fa-f]{6})'/gm)].map(
    (m) => [m[1], m[2]],
  ),
);
for (const t of ['deep', 'cream']) {
  if (!COLORS[t]) {
    console.error(`could not read the \`${t}\` token from src/lib/brand.ts`);
    process.exit(1);
  }
}

const INPUT = 'design-audit/tmp/horizon.svg';
const WAVE_OUTPUT = 'src/components/shared/horizon-wave.ts';
const SUN_OUTPUT = 'public/brand/sun-palm.svg';

const svg = readFileSync(INPUT, 'utf8');
const before = statSync(INPUT).size;

/** One decimal. On a drawing 2176px wide, 0.05px of error. */
const round = (s) => s.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));

/* ── 1. The two waves ────────────────────────────────────────────────────── */
const waves = [...svg.matchAll(/<path id="Vector(?:_2)?" d="([^"]+)"/g)].map((m) => round(m[1]));
if (waves.length !== 2) {
  console.error(`expected 2 wave paths, found ${waves.length}`);
  process.exit(1);
}

const viewBox = (svg.match(/viewBox="([^"]+)"/) ?? [])[1];

writeFileSync(
  WAVE_OUTPUT,
  `/**
 * The two wave paths of the brand book's «horizon» element.
 *
 * ⚠️ GENERATED by \`npm run horizon\` from node 2012:4491 of the Figma
 * («Rooftop at Riverside (Copy)»). Do not edit by hand: it gets overwritten.
 *
 * ⚠️ They go INLINE and not as a file because the wave has to stretch to the full
 * width of the screen and take its color from a token —it's the surface of the
 * section below emerging over the one above—. It's 1.4 KB, so inline
 * costs nothing. The medallion, which weighs 72 KB, is a separate file.
 */
export const HORIZON = {
  viewBox: '${viewBox}',
  /** The two wave layers. The second one sits a little lower and adds depth. */
  waves: [
${waves.map((d) => `    '${d}',`).join('\n')}
  ],
} as const;
`,
);

/* ── 2. The medallion ────────────────────────────────────────────────────── */
const sunGroup = svg.match(/<g id="Group 2134282044">([\s\S]*?)<\/g>\s*<\/g>/);
if (!sunGroup) {
  console.error('the medallion group was not found');
  process.exit(1);
}

/* The disc's `<circle>` carries its center and radius in attributes, not in a
   path: they have to be read to crop the medallion's viewBox. */
const c = sunGroup[1].match(/<circle[^>]*cx="([\d.]+)"[^>]*cy="([\d.]+)"[^>]*r="([\d.]+)"/);
if (!c) {
  console.error('the medallion circle was not found');
  process.exit(1);
}
const [, cx, cy, r] = c.map(Number);
/* The teeth stick out past the circle, so the canvas gets a margin. */
const margin = r * 0.18;
const side = (r + margin) * 2;

let body = round(sunGroup[1])
  .replace(/\s+id="[^"]*"/g, '')
  /*
   * ⚠️ ALL `<g>` TAGS ARE REMOVED, and this fixes a bug that produced a
   * BROKEN SVG for a while.
   *
   * The medallion group contains another nested group (the palm tree). The
   * regex that extracts it ends in `</g></g>`, so it swallowed the inner
   * one's closing tag and left the body with an unclosed `<g>`. The
   * resulting file wasn't valid XML: librsvg rejected it with «corrupt header»,
   * and the browser simply drew nothing — no console error.
   *
   * It could be balanced by counting tags, but that's unnecessary: verified
   * against the export, **neither of the two inner groups carries `transform`,
   * `clip-path`, `mask` or `style`**. They only group. Removing them leaves the
   * same drawing with fewer nodes and no way to become unbalanced.
   *
   * ⚠️ The OUTER frame's `clip-path` is also discarded, on purpose: it clipped
   * to the original 2176×233 canvas and here the medallion is reframed with
   * its own `viewBox`. Leaving it in would make it disappear.
   */
  .replace(/<\/?g[^>]*>/g, '')
  /*
   * The Figma colors to the site's, with the LITERAL VALUE and not with
   * `var(--color-*)`.
   *
   * ⚠️ And it has to be this way: CSS variables do NOT cross the boundary of an
   * `<img>`. An SVG loaded as an image is a separate document and doesn't see
   * the page's `:root`, so a `var(--color-deep)` inside always resolves to its
   * fallback. Using the variable would be writing something that looks
   * dynamic and never is — worse than the hex, because it lies.
   *
   * It's the same treatment `public/brand/tile-pattern.svg` already gets: brand
   * art with its color baked in. What CAN'T happen is these values drifting
   * out of sync with the palette, so they come from `COLORS` in `lib/brand.ts`
   * and aren't written by hand here.
   */
  .replace(/#003A3A/gi, COLORS.deep)
  .replace(/#FFF7ED/gi, COLORS.cream)
  .replace(/>\s+</g, '><')
  .trim();

/*
 * ⚠️ IT CARRIES `width` AND `height` IN ADDITION TO THE `viewBox`, and it's not
 * redundant: it's what gives the file an INTRINSIC SIZE.
 *
 * Without them, `next/image` returns an image the browser reports as
 * `naturalWidth: 0` and draws nothing. Measured: the `<img>` existed, `complete`
 * was `true`, the box was 163×163px, and the image was 0×0.
 *
 * And the failure mode was the worst one: no console error, no 404, the
 * response is 200. It just doesn't show. It stayed like that until I measured
 * it in the browser — twice I thought the problem was the z-index.
 *
 * The comparison that gave it away: `public/brand/isotype-truck.svg`, which does
 * render with `next/image`, carries `width="552" height="390"`. The SVGs Figma
 * exports have them; the ones I generated, until now, didn't.
 */
const sunSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${side.toFixed(0)}" height="${side.toFixed(0)}" viewBox="${(cx - r - margin).toFixed(1)} ${(cy - r - margin).toFixed(1)} ${side.toFixed(1)} ${side.toFixed(1)}" fill="none">${body}</svg>`;

/*
 * ⚠️ VALIDITY GUARD, and it exists because this script ALREADY generated a broken SVG.
 *
 * The extraction regex swallowed the nested group's `</g>` and left the body
 * with an open tag. The result wasn't valid XML, and the way it failed is the
 * dangerous one: **the browser draws nothing and reports nothing**. No console
 * error, no 404, no warning. The image is simply not there.
 *
 * I found it by chance because `sharp` does complain («corrupt header») when
 * trying to rasterize it for a contact sheet. Without that detour, the medallion
 * would have ended up invisible in production.
 *
 * So the script refuses to write an unbalanced file.
 */
for (const t of ['svg', 'g']) {
  const opens = (sunSvg.match(new RegExp(`<${t}[ >]`, 'g')) ?? []).length;
  const closes = (sunSvg.match(new RegExp(`</${t}>`, 'g')) ?? []).length;
  if (opens !== closes) {
    console.error(
      `❌ the medallion SVG ended up unbalanced: <${t}> opens ${opens} times and closes ${closes}.\n` +
        '   The file is not written. An invalid SVG draws NOTHING and gives no warning.',
    );
    process.exit(1);
  }
}

writeFileSync(SUN_OUTPUT, sunSvg);

const waveWeight = statSync(WAVE_OUTPUT).size;
const sunWeight = statSync(SUN_OUTPUT).size;
console.log(`input             ${(before / 1024).toFixed(1)} KB`);
console.log(`${WAVE_OUTPUT}  ${(waveWeight / 1024).toFixed(1)} KB  (inline)`);
console.log(`${SUN_OUTPUT}          ${(sunWeight / 1024).toFixed(1)} KB  (file, cached)`);
console.log(
  `total ${((waveWeight + sunWeight) / 1024).toFixed(1)} KB  (−${(100 - ((waveWeight + sunWeight) / before) * 100).toFixed(0)} %), and of that only ${(waveWeight / 1024).toFixed(1)} KB travel in the HTML`,
);
